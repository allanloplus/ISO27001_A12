#!/usr/bin/env python3
"""Generate narration audio for every line in src/scenes.js and write src/timing.js.

Voices (Microsoft Edge neural TTS, Taiwan Mandarin):
  A  Allan 老師  zh-TW-YunJheNeural（台灣男聲）
  R  助教阿拉蕾  zh-TW-HsiaoYuNeural（台灣女聲，調高音調）

Usage:  python3 tools/build_audio.py [--force]
"""
import asyncio
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

import certifi

# Behind a TLS-intercepting proxy the bundle in $SSL_CERT_FILE must be trusted.
if os.environ.get("SSL_CERT_FILE"):
    certifi.where = lambda: os.environ["SSL_CERT_FILE"]

import edge_tts  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
AUDIO = ROOT / "audio"
VOICES = {
    "A": dict(voice="zh-TW-YunJheNeural", rate="+4%", pitch="+0Hz"),
    "R": dict(voice="zh-TW-HsiaoYuNeural", rate="+10%", pitch="+30Hz"),
}


def load_scenes():
    js = "global.window={};require(process.argv[1]);console.log(JSON.stringify(window.SCENES))"
    out = subprocess.run(["node", "-e", js, str(ROOT / "src" / "scenes.js")],
                         check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def duration(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                          "-of", "csv=p=0", str(path)], check=True, capture_output=True, text=True)
    return round(float(out.stdout.strip()), 3)


TRIM = ("silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.06,areverse,"
        "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.15,areverse")


def trim(path):
    """Cut the leading/trailing silence edge-tts adds so the dialogue keeps its pace."""
    tmp = path.with_suffix(".tmp.mp3")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(path), "-af", TRIM,
                    "-c:a", "libmp3lame", "-b:a", "64k", str(tmp)], check=True)
    tmp.replace(path)


async def synth(text, who, path):
    v = VOICES[who]
    for attempt in range(4):
        try:
            c = edge_tts.Communicate(text, v["voice"], rate=v["rate"], pitch=v["pitch"],
                                     proxy=os.environ.get("HTTPS_PROXY"))
            await c.save(str(path))
            trim(path)
            return
        except Exception as e:  # network hiccups
            print(f"  retry {attempt + 1}: {e}", file=sys.stderr)
            await asyncio.sleep(2 ** attempt)
    raise RuntimeError(f"TTS failed: {path.name}")


async def main(force):
    AUDIO.mkdir(exist_ok=True)
    scenes = load_scenes()
    timing = []
    for si, sc in enumerate(scenes):
        row = []
        for li, ln in enumerate(sc["lines"]):
            text = ln.get("tts") or ln["say"]
            v = VOICES[ln["who"]]
            tag = hashlib.sha1(f'{text}|{v}'.encode()).hexdigest()[:8]
            name = f"s{si + 1:02d}_l{li + 1:02d}_{ln['who']}_{tag}.mp3"
            path = AUDIO / name
            if force or not path.exists() or path.stat().st_size == 0:
                for old in AUDIO.glob(f"s{si + 1:02d}_l{li + 1:02d}_*.mp3"):
                    old.unlink()
                print("TTS", name)
                await synth(text, ln["who"], path)
            row.append({"src": f"audio/{name}", "dur": duration(path)})
        timing.append(row)
    # drop audio files no longer referenced
    used = {t["src"].split("/")[1] for row in timing for t in row}
    for f in AUDIO.glob("*.mp3"):
        if f.name not in used:
            f.unlink()
    (ROOT / "src" / "timing.js").write_text(
        "// generated by tools/build_audio.py — do not edit\nwindow.TIMING = "
        + json.dumps(timing, ensure_ascii=False) + ";\n", encoding="utf-8")
    total = sum(t["dur"] for row in timing for t in row)
    print(f"{sum(len(r) for r in timing)} lines, speech {total / 60:.1f} min")


if __name__ == "__main__":
    asyncio.run(main("--force" in sys.argv))
